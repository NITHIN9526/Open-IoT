import assert from 'node:assert/strict';
import { once } from 'node:events';
import { createServer } from 'node:http';
import { randomBytes } from 'node:crypto';
import { chromium, expect } from '@playwright/test';
import { createApp } from '../server/app.js';
import { createTestDb } from './database.js';
const db = await createTestDb();
let app, browser;
const server = createServer((req,res) => app(req,res));
server.listen(0,'127.0.0.1'); await once(server,'listening');
const origin = `http://127.0.0.1:${server.address().port}`;
app = await createApp({ db, origin, encryptionKey:randomBytes(32), bcryptRounds:4, disableLimits:true });
try {
  browser = await chromium.launch({ headless:true, args:['--no-sandbox'], executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE || undefined });
  const page = await browser.newPage({ viewport:{width:390,height:844} });
  const errors=[]; page.on('pageerror', e=>{errors.push(e.message);console.error(e.message);});
  const authResponse = await page.request.post(origin+'/api/auth/register',{headers:{Origin:origin},data:{name:'Firmware tester',email:'firmware@example.com',password:'test-password-123'}});
  const auth = await authResponse.json();
  const headers = {Origin:origin,'X-CSRF-Token':auth.csrfToken};
  const created = await (await page.request.post(origin+'/api/devices',{headers,data:{name:'Relay board',deviceType:'esp32'}})).json();
  const id=created.device.id;
  assert.equal((await page.request.post(origin+`/api/devices/${id}/pins`,{headers,data:{pin:'V7',label:'Kitchen',dataType:'boolean',direction:'output'}})).status(),201);
  await page.goto(origin+'/docs?tab=start');
  await page.getByLabel('Device',{exact:true}).selectOption(id);
  await expect(page.getByLabel('Virtual pin 2',{exact:true})).toHaveValue('V7');
  assert.equal(await page.getByLabel('Virtual pin 1',{exact:true}).locator('option').count(),2);
  await page.getByLabel('Device token',{exact:true}).fill('A'.repeat(43));
  await page.getByLabel('Wi-Fi name',{exact:true}).fill('Home "Wi-Fi"');
  await page.getByLabel('Wi-Fi password',{exact:true}).fill('local-wifi-secret');
  await page.getByLabel('Server LAN IP',{exact:true}).fill('127.0.0.1');
  await page.getByRole('button',{name:'Generate code',exact:true}).click();
  await expect(page.getByRole('alert')).toContainText('private IPv4');
  await page.getByLabel('Server LAN IP',{exact:true}).fill('192.168.1.50');
  await page.getByLabel('GPIO 2',{exact:true}).selectOption('23');
  await page.getByRole('button',{name:'Generate code',exact:true}).click();
  await expect(page.getByRole('alert')).toContainText('different GPIO');
  await page.getByLabel('GPIO 2',{exact:true}).selectOption('22');
  const requests=[]; page.on('request',req=>{if(req.method()!=='GET') requests.push(req.url());});
  await page.getByRole('button',{name:'Generate code',exact:true}).click();
  await expect(page.getByLabel('src/main.cpp code',{exact:true})).toBeVisible();
  await page.locator('summary').filter({hasText:'include/secrets.h'}).click();
  await expect(page.getByLabel('include/secrets.h code',{exact:true})).toHaveValue(/\{"V7", 22, true\}/);
  // Exercise insecure-context fallback without relying on OS clipboard permission.
  await page.evaluate(()=>{Object.defineProperty(navigator,'clipboard',{value:undefined,configurable:true}); document.execCommand=command=>command==='copy';});
  await page.getByRole('button',{name:'Copy include/secrets.h',exact:true}).click();
  await expect(page.getByText('Copied!',{exact:true})).toBeVisible();
  await page.evaluate(()=>{document.execCommand=()=>false;});
  await page.getByRole('button',{name:'Copy include/secrets.h',exact:true}).click();
  await expect(page.getByText('Copy blocked.',{exact:false})).toBeVisible();
  assert.deepEqual(requests,[]);
  assert.equal(await page.evaluate(()=>Object.values(localStorage).some(v=>v.includes('local-wifi-secret'))),false);
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.getByLabel('GPIO 2',{exact:true}).selectOption('21');
  await expect(page.getByLabel('src/main.cpp code',{exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'Clear credentials',exact:true}).click();
  await expect(page.getByLabel('Wi-Fi password',{exact:true})).toHaveValue('');
  await expect(page.getByLabel('Device token',{exact:true})).toHaveValue('');
  assert.deepEqual(errors,[]);
  console.log('Firmware generator browser checks passed: real device pins, validation, generation, clipboard fallback, clearing, no credential requests and mobile layout.');
} finally { await browser?.close(); await new Promise(r=>{server.close(r);server.closeAllConnections();}); await db.raw.close(); }

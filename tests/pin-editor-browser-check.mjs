import assert from 'node:assert/strict';
import {once} from 'node:events';
import {createServer} from 'node:http';
import {randomBytes} from 'node:crypto';
import {chromium,expect} from '@playwright/test';
import {createApp} from '../server/app.js';
import {createTestDb} from './database.js';
import {attachLive} from '../server/live.js';
const db=await createTestDb();
let app;
const server=createServer((req,res)=>app(req,res));
server.listen(0,'127.0.0.1');await once(server,'listening');
const origin=`http://127.0.0.1:${server.address().port}`;
app=await createApp({db,origin,encryptionKey:randomBytes(32),bcryptRounds:4,disableLimits:true});
const stop=attachLive(server,{db,origin,intervalMs:100});
let browser;
try {
 browser=await chromium.launch({headless:true,args:['--no-sandbox'],executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE||undefined});
 const page=await browser.newPage({viewport:{width:1366,height:900}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const registration=await page.request.post(origin+'/api/auth/register',{headers:{Origin:origin},data:{name:'Pin editor tester',email:'pin-editor@example.com',password:'test-password-123'}});
 assert.equal(registration.status(),201);
 const auth=await registration.json();
 const created=await page.request.post(origin+'/api/devices',{headers:{Origin:origin,'X-CSRF-Token':auth.csrfToken},data:{name:'Four channel board',deviceType:'esp32'}});
 assert.equal(created.status(),201);const {device}=await created.json();
 await page.goto(origin+'/dashboard/devices/'+device.id);
 await expect(page.getByRole('article')).toHaveCount(3);
 await page.getByRole('button',{name:'Edit Power V1',exact:true}).click();
 await page.getByLabel('Label',{exact:true}).fill('Bedroom light');
 await page.getByRole('button',{name:'Save changes',exact:true}).click();
 await expect(page.getByRole('article',{name:'Bedroom light V1',exact:true})).toBeVisible();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await page.getByRole('button',{name:'Edit Brightness V2',exact:true}).click();
 await page.getByLabel('Data type',{exact:true}).selectOption('boolean');
 await expect(page.getByLabel('Unit (optional)',{exact:true})).toHaveValue('');
 await page.getByLabel('Virtual pin',{exact:true}).selectOption('V3');
 await page.getByLabel('Label',{exact:true}).fill('Kitchen light');
 await expect(page.getByRole('button',{name:'Save changes',exact:true})).toBeDisabled();
 await page.getByLabel('I understand and want to reset this pin').check();
 await page.getByRole('button',{name:'Save changes',exact:true}).click();
 await expect(page.getByRole('article',{name:'Kitchen light V3',exact:true})).toBeVisible();
 await expect(page.getByRole('button',{name:'Turn Kitchen light on',exact:true})).toBeVisible();
 // Cancel removal, then remove the seeded sensor and ensure the chart disappears.
 await page.getByRole('button',{name:'Remove Temperature V0',exact:true}).click();
 await page.getByRole('button',{name:'Cancel',exact:true}).click();
 await expect(page.getByRole('article')).toHaveCount(3);
 await page.getByRole('button',{name:'Remove Temperature V0',exact:true}).click();
 await page.getByLabel('Remove this pin and its stored data').check();
 await page.getByRole('button',{name:'Remove pin',exact:true}).click();
 await expect(page.getByRole('article')).toHaveCount(2);
 await expect(page.getByRole('heading',{name:'Signal history',exact:true})).toHaveCount(0);
 await page.reload();
 await expect(page.getByRole('article',{name:'Kitchen light V3',exact:true})).toBeVisible();
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Edit Kitchen light V3',exact:true}).click();
 await expect(page.getByRole('dialog')).toBeVisible();
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'Mobile page overflows');
 await page.screenshot({path:'/tmp/open-iot-pin-editor-mobile.png',fullPage:true});
 await page.getByRole('button',{name:'Cancel',exact:true}).click();
 for(const name of ['Bedroom light V1','Kitchen light V3']) {
  await page.getByRole('button',{name:'Remove '+name,exact:true}).click();
  await page.getByLabel('Remove this pin and its stored data').check();
  await page.getByRole('button',{name:'Remove pin',exact:true}).click();
  await expect(page.getByRole('article',{name,exact:true})).toHaveCount(0);
 }
 await expect(page.getByText('No virtual pins yet.',{exact:false})).toBeVisible();
 await page.getByRole('button',{name:'Add virtual pin',exact:true}).click();
 await page.getByLabel('Label',{exact:true}).fill('Porch light');
 await page.getByLabel('Virtual pin',{exact:true}).selectOption('V31');
 await page.getByRole('button',{name:'Add pin',exact:true}).click();
 await expect(page.getByRole('article',{name:'Porch light V31',exact:true})).toBeVisible();
 assert.deepEqual(errors,[]);
 console.log('Pin editor browser checks passed: edit, reset, removal/cancel, persistence, empty state, V31 and phone layout.');
} finally {await browser?.close();stop();await new Promise(r=>server.close(r));await db.raw.close();}
